/**
 * Mod Form Documentation — Complete field reference for mod creators and moderators.
 *
 * Structure: intro page + one self-contained page per platform (9) + moderator + team.
 * Each platform page includes the common fields first, then its platform-specific fields.
 *
 * Block types:
 *   'text'    — plain paragraph
 *   'list'    — unordered list
 *   'example' — highlighted example box (legacy, kept for compatibility)
 *   'good'    — correct-examples box (green)
 *   'bad'     — wrong-examples box (red, each with the reason)
 *   'tip'     — helpful suggestion
 *   'warn'    — warning / common mistake
 *   'field'   — field documentation (label, description, options, examples)
 *   'sub'     — sub-heading
 */

export interface DocBlock {
  type: 'text' | 'list' | 'example' | 'good' | 'bad' | 'tip' | 'warn' | 'field' | 'sub' | 'table'
  label?: string
  text?: string
  items?: string[]
  value?: string
  options?: { label: string; desc: string }[]
  headers?: string[]
  rows?: string[][]
}

export interface DocSection {
  id: string
  title: string
  icon?: string
  children: DocBlock[]
}

export interface DocPage {
  id: string
  title: string
  icon?: string
  intro?: string
  sections: DocSection[]
}

